#include <stdio.h>

int main() {
    // Different data types in C
    int age = 20;                // Integer type
    float height = 5.9;          // Floating point type
    double weight = 70.55;       // Double precision floating point
    char grade = 'A';            // Character type

    // Printing values
    printf("Age (int)       : %d\n", age);
    printf("Height (float)  : %.2f\n", height);
    printf("Weight (double) : %.2lf\n", weight);
    printf("Grade (char)    : %c\n", grade);

    return 0;
}
